import { designsService } from './designs.service';
import { designSessionsService } from './designSessions.service';
import { designSessionsRepository } from '../repositories';
import { enqueueDesignJob } from '../lib/queue';
import { setupTestDatabase, TestDatabase } from '../test/testDatabase';
import { createUser, UNKNOWN_ID } from '../test/fixtures';

jest.mock('../lib/queue', () => ({ enqueueDesignJob: jest.fn().mockResolvedValue({ id: 'queued' }) }));
jest.mock('../lib/s3', () => ({
  getPresignedUploadUrl: jest.fn(async (key: string) => ({ url: `https://s3.test/${key}`, expiresAt: new Date('2030-01-01T00:00:00Z') })),
  headObject: jest.fn(async () => ({ exists: true, contentType: 'image/png', contentLength: 1024 })),
  verifyObjectOwnership: jest.fn(async (key: string, userId: string, sessionId: string) =>
    key.startsWith(`users/${userId}/sessions/${sessionId}/`)),
  isAllowedImageType: (mime: string) => ['image/jpeg', 'image/png', 'image/webp'].includes(mime),
  MAX_IMAGE_BYTES: 15 * 1024 * 1024,
}));

let database: TestDatabase;
let userId: string;
let otherUserId: string;

beforeAll(async () => { database = await setupTestDatabase(); });
afterAll(async () => { await database.close(); });
beforeEach(async () => {
  await database.reset();
  jest.clearAllMocks();
  userId = (await createUser({ tier: 'premium' })).id;
  otherUserId = (await createUser()).id;
});

const DESIGN = { title: 'Smart casual', items: [{ label: 'shirt' }, { label: 'chinos' }], tips: ['tuck it in'], score: 0.8 };

async function createJob(owner = userId) {
  const { jobId } = await designsService.createJob(owner, 'free', {
    vertical: 'wardrobe', imageKeys: ['uploads/a.jpg', 'uploads/b.jpg'], contextData: { occasion: 'work' },
  });
  return jobId;
}

describe('design jobs (legacy pipeline)', () => {
  it('creates a pending job and enqueues it', async () => {
    const result = await designsService.createJob(userId, 'pro', {
      vertical: 'room', imageKeys: ['uploads/a.jpg'], contextData: { occasion: 'party' },
    });

    expect(result).toMatchObject({ status: 'pending', estimatedSeconds: 5 });
    expect(enqueueDesignJob).toHaveBeenCalledWith(expect.objectContaining({ jobId: result.jobId, userId, tier: 'pro' }));

    const job = await designsService.getJob(result.jobId, userId);
    expect(job).toMatchObject({
      id: result.jobId, userId, vertical: 'room', status: 'pending',
      imageKeys: ['uploads/a.jpg'], contextData: { occasion: 'party' },
      result: null, errorMsg: null, completedAt: null,
    });
  });

  it('enforces ownership and hides unknown ids', async () => {
    const jobId = await createJob();
    await expect(designsService.getJob(jobId, otherUserId)).rejects.toMatchObject({ statusCode: 403 });
    await expect(designsService.getJob(UNKNOWN_ID, userId)).rejects.toMatchObject({ statusCode: 404 });
    await expect(designsService.getJob('nope', userId)).rejects.toMatchObject({ statusCode: 404 });
  });

  it('records completion with the result payload', async () => {
    const jobId = await createJob();
    const result = { designs: [DESIGN], vertical: 'wardrobe', itemCount: 2 };

    const updated = await designsService.updateJobStatus(jobId, 'completed', result);

    expect(updated).toMatchObject({ status: 'completed', result });
    expect(updated!.completedAt).toBeInstanceOf(Date);
  });

  it('records failure without touching completedAt', async () => {
    const jobId = await createJob();
    const updated = await designsService.updateJobStatus(jobId, 'failed', undefined, 'detector exploded');
    expect(updated).toMatchObject({ status: 'failed', errorMsg: 'detector exploded', completedAt: null });
  });

  it('treats a status update for a non-job id as a no-op', async () => {
    await expect(designsService.updateJobStatus(UNKNOWN_ID, 'completed')).resolves.toBeNull();
    await expect(designsService.updateJobStatus('665a1b2c3d4e5f6a7b8c9d0e', 'completed')).resolves.toBeNull();
  });

  it('lists summaries newest first with paging totals', async () => {
    await createJob();
    await createJob();
    await createJob(otherUserId);

    const page = await designsService.listJobs(userId, { page: 1, limit: 1 });

    expect(page).toMatchObject({ total: 2, totalPages: 2, page: 1, limit: 1 });
    expect(Object.keys(page.jobs[0]).sort()).toEqual(['completedAt', 'createdAt', 'id', 'status', 'vertical']);
  });
});

describe('saved designs', () => {
  it('saves a design generated by a legacy job', async () => {
    const jobId = await createJob();
    const saved = await designsService.saveDesign(userId, jobId, DESIGN);

    expect(saved).toMatchObject({
      userId, jobId, title: 'Smart casual', items: DESIGN.items, tips: ['tuck it in'], score: 0.8,
      isFavorite: false, tags: [], mockupUrl: null, explanation: null,
    });
  });

  it('saves a design generated by a v1 session, reporting the session as jobId', async () => {
    const session = await designSessionsService.createSession(userId, { vertical: 'wardrobe' });

    const saved = await designsService.saveDesign(userId, session.session_id, DESIGN);

    expect(saved.jobId).toBe(session.session_id);
    const { rows } = await database.db.query('select job_id, session_id from saved_designs where id = $1', [saved.id]);
    expect(rows[0]).toEqual({ job_id: null, session_id: session.session_id });
  });

  it('refuses to save against a job or session owned by someone else', async () => {
    const jobId = await createJob(otherUserId);
    const session = await designSessionsService.createSession(otherUserId, { vertical: 'room' });

    await expect(designsService.saveDesign(userId, jobId, DESIGN)).rejects.toMatchObject({ statusCode: 403 });
    await expect(designsService.saveDesign(userId, session.session_id, DESIGN)).rejects.toMatchObject({ statusCode: 403 });
    await expect(designsService.saveDesign(userId, UNKNOWN_ID, DESIGN)).rejects.toMatchObject({ statusCode: 404 });
  });

  it('toggles favourite and filters on it', async () => {
    const jobId = await createJob();
    const a = await designsService.saveDesign(userId, jobId, DESIGN);
    await designsService.saveDesign(userId, jobId, { ...DESIGN, title: 'Other' });

    expect((await designsService.toggleFavorite(a.id, userId))!.isFavorite).toBe(true);
    expect((await designsService.getSavedDesigns(userId, { page: 1, limit: 20, favorite: true })).total).toBe(1);
    expect((await designsService.getSavedDesigns(userId, { page: 1, limit: 20, favorite: false })).total).toBe(1);
    expect((await designsService.getSavedDesigns(userId, { page: 1, limit: 20 })).total).toBe(2);

    expect((await designsService.toggleFavorite(a.id, userId))!.isFavorite).toBe(false);
    await expect(designsService.toggleFavorite(a.id, otherUserId)).rejects.toMatchObject({ statusCode: 403 });
  });

  it('deletes only for the owner', async () => {
    const saved = await designsService.saveDesign(userId, await createJob(), DESIGN);

    await expect(designsService.deleteSavedDesign(saved.id, otherUserId)).rejects.toMatchObject({ statusCode: 403 });
    await designsService.deleteSavedDesign(saved.id, userId);
    await expect(designsService.deleteSavedDesign(saved.id, userId)).rejects.toMatchObject({ statusCode: 404 });
  });
});

describe('design sessions (v1 pipeline)', () => {
  it('creates a session whose upload keys embed the user and session ids', async () => {
    const result = await designSessionsService.createSession(userId, {
      vertical: 'wardrobe', occasion: 'work', imageCount: 2, climate: { temperature_c: 31 },
    });

    expect(result.status).toBe('created');
    expect(result.upload_urls).toHaveLength(2);
    for (const upload of result.upload_urls) {
      expect(upload.object_key).toMatch(new RegExp(`^users/${userId}/sessions/${result.session_id}/images/img_[0-9a-f]+/source\\.png$`));
      expect(upload.expires_at).toBe('2030-01-01T00:00:00.000Z');
    }

    const session = await designSessionsService.getSession(result.session_id, userId);
    expect(session).toMatchObject({
      session_id: result.session_id, status: 'created', progress: 5, vertical: 'wardrobe',
      designs: [], warnings: [], artifacts: [], error: null,
      steps: {
        quality: 'pending', detection: 'pending', attributes: 'pending', context: 'pending',
        permutations: 'pending', embeddings: 'pending', reasoning: 'pending', mockups: 'pending',
      },
    });
    expect(session.sourceImages.map((s) => s.qualityStatus)).toEqual(['pending', 'pending']);
  });

  it('enforces ownership', async () => {
    const { session_id } = await designSessionsService.createSession(userId, { vertical: 'room' });
    await expect(designSessionsService.getSession(session_id, otherUserId)).rejects.toMatchObject({ statusCode: 403 });
    await expect(designSessionsService.cancelSession(session_id, otherUserId)).rejects.toMatchObject({ statusCode: 403 });
    await expect(designSessionsService.getSession(UNKNOWN_ID, userId)).rejects.toMatchObject({ statusCode: 404 });
  });

  it('verifies uploads, queues the pipeline with the owner\'s tier, and refuses a second completion', async () => {
    const created = await designSessionsService.createSession(userId, { vertical: 'wardrobe', imageCount: 2 });
    const imageIds = created.upload_urls.map((u) => u.image_id);

    const result = await designSessionsService.completeImages(created.session_id, userId, imageIds);

    expect(result).toMatchObject({ status: 'queued', image_count: 2 });
    expect(enqueueDesignJob).toHaveBeenCalledWith(expect.objectContaining({
      sessionId: created.session_id, jobId: created.session_id, userId, tier: 'premium',
      imageKeys: created.upload_urls.map((u) => u.object_key),
    }));

    const session = await designSessionsRepository.findById(created.session_id);
    expect(session).toMatchObject({ status: 'queued', progress: 10 });
    expect(session!.sourceImages[0]).toMatchObject({ contentType: 'image/png', byteSize: 1024 });

    await expect(designSessionsService.completeImages(created.session_id, userId, imageIds))
      .rejects.toMatchObject({ statusCode: 400 });
  });

  it('rejects image ids that are not part of the session', async () => {
    const created = await designSessionsService.createSession(userId, { vertical: 'wardrobe' });
    await expect(designSessionsService.completeImages(created.session_id, userId, ['img_other']))
      .rejects.toMatchObject({ statusCode: 400 });
    expect(enqueueDesignJob).not.toHaveBeenCalled();
  });

  it('lists sessions with image/design counts', async () => {
    const { session_id } = await designSessionsService.createSession(userId, { vertical: 'garden', imageCount: 3 });
    await designSessionsRepository.update(session_id, { designs: [{ id: 'd1' }, { id: 'd2' }] });
    await designSessionsService.createSession(otherUserId, { vertical: 'room' });

    const page = await designSessionsService.listSessions(userId);

    expect(page.total).toBe(1);
    expect(page.sessions[0]).toMatchObject({ session_id, vertical: 'garden', imageCount: 3, designCount: 2 });
  });

  it('cancels', async () => {
    const { session_id } = await designSessionsService.createSession(userId, { vertical: 'room' });
    await designSessionsService.cancelSession(session_id, userId);
    expect(await designSessionsService.getSession(session_id, userId)).toMatchObject({ status: 'cancelled', progress: 0 });
  });
});

describe('pipeline step tracking', () => {
  let sessionId: string;
  beforeEach(async () => {
    sessionId = (await designSessionsService.createSession(userId, { vertical: 'wardrobe' })).session_id;
  });

  it('maps a running step to the client-facing status and advances progress', async () => {
    const session = await designSessionsService.updateStep(sessionId, 'detection', 'running');
    expect(session).toMatchObject({ status: 'detecting', progress: 20 });
    expect(session!.steps).toMatchObject({ detection: 'running', quality: 'pending' });
  });

  it('never moves progress backwards', async () => {
    await designSessionsService.updateStep(sessionId, 'reasoning', 'completed');
    const session = await designSessionsService.updateStep(sessionId, 'quality', 'completed');
    expect(session!.progress).toBe(75);
  });

  it('keeps every status when steps finish concurrently', async () => {
    await Promise.all([
      designSessionsService.updateStep(sessionId, 'quality', 'completed'),
      designSessionsService.updateStep(sessionId, 'context', 'completed'),
      designSessionsService.updateStep(sessionId, 'detection', 'completed'),
    ]);
    const session = await designSessionsRepository.findById(sessionId);
    expect(session!.steps).toMatchObject({ quality: 'completed', context: 'completed', detection: 'completed' });
  });

  it('stores step output and completes the session after mockups', async () => {
    await designSessionsService.updateStep(sessionId, 'context', 'completed', { inferredContext: { season: 'dry' } });
    await designSessionsService.updateStep(sessionId, 'reasoning', 'completed', { designs: [DESIGN] });
    const artifacts = [{ id: 'art_1', permutationId: 'perm_1', objectKey: 'users/u/mockups/1.png', contentType: 'image/png' }];
    const session = await designSessionsService.updateStep(sessionId, 'mockups', 'completed', { artifacts });

    expect(session).toMatchObject({
      status: 'completed', progress: 100, inferredContext: { season: 'dry' }, designs: [DESIGN], artifacts,
    });
    expect(session!.completedAt).toBeInstanceOf(Date);
  });

  it('marks the session failed when a step reports an error', async () => {
    const error = { code: 'PIPELINE_FAILED', message: 'boom' };
    const session = await designSessionsService.updateStep(sessionId, 'detection', 'failed', { error });
    expect(session).toMatchObject({ status: 'failed', error });
    expect(session!.steps.detection).toBe('failed');
  });

  it('appends warnings atomically', async () => {
    await Promise.all([
      designSessionsRepository.appendWarnings(sessionId, ['a']),
      designSessionsRepository.appendWarnings(sessionId, ['b', 'c']),
    ]);
    const session = await designSessionsRepository.findById(sessionId);
    expect([...session!.warnings].sort()).toEqual(['a', 'b', 'c']);
  });

  it('returns null for a session that no longer exists', async () => {
    await expect(designSessionsService.updateStep(UNKNOWN_ID, 'quality', 'running')).resolves.toBeNull();
  });
});
