/**
 * Domain entities — plain data, no persistence behaviour.
 *
 * Property names are the camelCase the HTTP API has always returned; the
 * repositories map them to snake_case columns. `id`s are uuids. Timestamps are
 * `Date`s here and ISO-8601 strings once serialised to JSON.
 */

export type Tier = 'free' | 'premium' | 'pro';
export type Vertical = 'wardrobe' | 'room' | 'garden';

export const VERTICALS: readonly Vertical[] = ['wardrobe', 'room', 'garden'];

// ── User ─────────────────────────────────────────────────────────────────────

export interface User {
  id:        string;
  email:     string;
  name:      string | null;
  avatarUrl: string | null;
  tier:      Tier;
  isActive:  boolean;
  createdAt: Date;
  updatedAt: Date;
}

/** Only the auth service may see the hash; it is never part of `User`. */
export interface UserCredentials extends User {
  passwordHash: string | null;
}

export interface RefreshToken {
  id:        string;
  userId:    string;
  tokenHash: string;
  expiresAt: Date;
  createdAt: Date;
}

export interface Location {
  lat:      number;
  lon:      number;
  city?:    string;
  country?: string;
}

export interface UserPreferences {
  id:          string;
  userId:      string;
  occupation:  string | null;
  styleGoals:  string[];
  occasions:   string[];
  culturalCtx: string | null;
  location:    Location | null;
  createdAt:   Date;
  updatedAt:   Date;
}

// ── Subscription ─────────────────────────────────────────────────────────────

export type SubStatus = 'active' | 'inactive' | 'past_due' | 'cancelled';

export interface Subscription {
  id:                   string;
  userId:               string;
  stripeCustomerId:     string | null;
  stripeSubscriptionId: string | null;
  status:               SubStatus;
  currentPeriodEnd:     Date | null;
  cancelAtPeriodEnd:    boolean;
  createdAt:            Date;
  updatedAt:            Date;
}

// ── Catalog ──────────────────────────────────────────────────────────────────

export interface ColorSwatch {
  hex: string;
  rgb: { r: number; g: number; b: number };
}

export interface ColorInfo {
  dominant: ColorSwatch;
  palette:  ColorSwatch[];
  mood:     string;
}

export interface CatalogItem {
  id:           string;
  userId:       string;
  vertical:     Vertical;
  label:        string;
  category:     string;
  color:        ColorInfo;
  texture:      string | null;
  pattern:      string | null;
  imageKey:     string;
  thumbnailKey: string | null;
  confidence:   number;
  /** Free-form AI extras (bbox, material, …). */
  attributes:   Record<string, unknown>;
  tags:         string[];
  styleTags:    string[];
  isActive:     boolean;
  createdAt:    Date;
  updatedAt:    Date;
}

// ── Design jobs (legacy pipeline) ────────────────────────────────────────────

export type JobStatus = 'pending' | 'processing' | 'completed' | 'failed';

export interface DesignJob {
  id:          string;
  userId:      string;
  vertical:    Vertical;
  status:      JobStatus;
  imageKeys:   string[];
  contextData: Record<string, unknown>;
  result:      Record<string, unknown> | null;
  errorMsg:    string | null;
  completedAt: Date | null;
  createdAt:   Date;
  updatedAt:   Date;
}

export type DesignJobSummary = Pick<DesignJob, 'id' | 'vertical' | 'status' | 'createdAt' | 'completedAt'>;

// ── Saved designs ────────────────────────────────────────────────────────────

export interface SavedDesign {
  id:          string;
  userId:      string;
  /**
   * The legacy job or v1 session the design was generated by (the API has
   * always called this `jobId`). Null once that source has been deleted.
   */
  jobId:       string | null;
  title:       string | null;
  items:       Record<string, unknown>[];
  mockupUrl:   string | null;
  explanation: string | null;
  tips:        string[];
  score:       number;
  isFavorite:  boolean;
  tags:        string[];
  createdAt:   Date;
}

export interface DeviceToken {
  id:        string;
  userId:    string;
  token:     string;
  platform:  'ios' | 'android';
  createdAt: Date;
}

// ── Design sessions (v1 pipeline) ────────────────────────────────────────────

export type SessionStatus =
  | 'created'         // after POST /v1/design-sessions
  | 'uploading'       // presigned URLs issued, awaiting client upload
  | 'queued'          // images confirmed, job enqueued
  | 'quality_review'  // quality guard failed, needs retake
  | 'detecting' | 'extracting' | 'permuting' | 'embedding' | 'reasoning' | 'composing'
  | 'completed'
  | 'failed'
  | 'cancelled';

export type StepStatus = 'pending' | 'running' | 'completed' | 'failed' | 'skipped';

export type SessionStep =
  | 'quality' | 'detection' | 'attributes' | 'context'
  | 'permutations' | 'embeddings' | 'reasoning' | 'mockups';

export interface SourceImage {
  imageId:        string;   // img_…
  objectKey:      string;   // users/<userId>/sessions/<sessionId>/images/<imageId>/source.png
  uploadUrl?:     string;   // presigned PUT, issued at creation
  /** ISO-8601 (this lives inside a jsonb column, so it is a string, not a Date). */
  expiresAt?:     string;
  contentType?:   string;
  byteSize?:      number;
  width?:         number;
  height?:        number;
  sha256?:        string;
  qualityResult?: Record<string, unknown> | null;
  qualityStatus?: 'pending' | 'passed' | 'failed' | 'error';
}

export interface SessionArtifact {
  id:            string;
  permutationId: string;
  objectKey:     string;
  contentType:   string;
  sha256?:       string;
  width?:        number;
  height?:       number;
  url?:          string;
}

export interface SessionError {
  code:        string;
  message:     string;
  details?:    unknown;
  request_id?: string;
}

export interface DesignSession {
  id:              string;
  userId:          string;
  vertical:        Vertical;
  status:          SessionStatus;
  progress:        number; // 0–100
  steps:           Record<string, StepStatus>;
  /** Explicit user inputs (occasion, culture, climate, preferences, …). */
  inputContext:    Record<string, unknown>;
  /** Output of the context-inference service. */
  inferredContext: Record<string, unknown> | null;
  sourceImages:    SourceImage[];
  pipelineVersion: string;
  correlationId:   string;
  warnings:        string[];
  /** Final LLM designs. */
  designs:         Record<string, unknown>[];
  artifacts:       SessionArtifact[];
  error:           SessionError | null;
  completedAt:     Date | null;
  createdAt:       Date;
  updatedAt:       Date;
}
